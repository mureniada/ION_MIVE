@guarded
def test_t74_parameter_values_are_canonical_typed_strings():
    contract = _contract()
    built = identity.build_identity(
        "dispatch", _raw_of(contract, "dispatch", "dispatch-v1"), contract)
    by_key = {p["key"]: p for p in built["basis"]["parameters"]}

    assert by_key["configurable"] == {"key": "configurable", "value": "false",
                                      "value_type": "boolean"}
    assert by_key["order"]["value"] == "gemini,openai"   # one representation per value
    assert all(isinstance(p["value"], str) for p in built["basis"]["parameters"])
    # keys sorted ascending, unique
    keys = [p["key"] for p in built["basis"]["parameters"]]
    assert keys == sorted(keys, key=lambda k: k.encode("utf-16-be"))
    assert len(set(keys)) == len(keys)

    # a value whose Python type disagrees with the declared type is refused
    with raises(IdentityError):
        identity.build_identity(
            "dispatch",
            dict(_raw_of(contract, "dispatch", "dispatch-v1"), configurable="false"),
            contract)


# --------------------------------------------------------------------------- #
# T86 — variant selection
# --------------------------------------------------------------------------- #

@guarded
def test_t86_selection_is_unique_and_has_no_default_or_fallback():
    contract = _contract()
    entry = _dimension(contract, "implementation")
    assert identity.select_variant(entry, {}) == "impl-all"

    # Ambiguous: two variants that can both match is an error, not a precedence rule.
    ambiguous = copy.deepcopy(entry)
    clone = copy.deepcopy(ambiguous["variants"][0])
    clone["variant_id"] = "impl-clone"
    ambiguous["variants"].append(clone)
    with raises(VariantSelectionError):
        identity.select_variant(ambiguous, {})

    # Unmatched: no variant matches, and no default variant is applied.
    unmatched = copy.deepcopy(entry)
    unmatched["variants"][0]["selector"] = [
        {"discriminator": "component", "match": "exact", "value": "never-matches"}]
    with raises(VariantSelectionError):
        identity.select_variant(unmatched, {"component": "retrieval"})


