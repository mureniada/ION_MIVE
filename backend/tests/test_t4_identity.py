# --------------------------------------------------------------------------- #

@guarded
def test_a_security_material_key_is_refused_not_silently_omitted():
    """§2A S5: an omission would produce a basis claiming a completeness it lacks."""
    contract = copy.deepcopy(_contract())
    entry = _dimension(contract, "implementation")
    variant = entry["variants"][0]
    variant["keys"][0]["key"] = "openai_api_key"
    variant["keys"].sort(key=lambda k: k["key"].encode("utf-16-be"))

    raw = copy.deepcopy(_raw_of(_contract(), "implementation", "implementation-v1"))
    raw["distributions"]["openai_api_key"] = raw["distributions"].pop("google_genai_version")

    with raises(SecretBoundaryViolation):
        identity.build_identity("implementation", raw, contract)


@guarded
def test_an_unobservable_dimension_refuses_a_locally_set_value():
    """A contract gap is reported, not absorbed: the contract says nothing is set."""
