"""Identity construction under the frozen contract — T70, T71, T72, T79, T80, T86.

Every sensitivity assertion here mutates **raw input** and invokes the builder
against the resolved contract. No test substitutes a computed digest, hand-writes a
variant id, or edits a stored basis: doing so would demonstrate that a field can be
changed, which nobody doubts, rather than that the identity is constructed from the
configuration, which is the claim (I14).

Every test runs under `netguard`'s `guarded` decorator with credentials absent.
"""

from __future__ import annotations

import base64
import copy
import hashlib

from t4 import identity, jcs, manifest
from t4.identity import IdentityError, SecretBoundaryViolation, VariantSelectionError
from tests.netguard import guarded
from tests.util import raises


def _contract() -> dict:
    _path, raw, _digest = manifest.resolve(manifest.ROLE_CONTRACT)
    return jcs.parse(raw)


def _dimension(contract: dict, name: str) -> dict:
    return next(d for d in contract["dimensions"] if d["dimension"] == name)


def _raw_of(contract: dict, dimension: str, vector_id: str) -> dict:
    vector = next(v for v in _dimension(contract, dimension)["vectors"]
                  if v["vector_id"] == vector_id)
    return jcs.parse(base64.b64decode(vector["raw_input_b64"], validate=True))


# --------------------------------------------------------------------------- #
# T80 — every dimension and every variant, reproduced end to end
# --------------------------------------------------------------------------- #

@guarded
def test_t80_builder_reproduces_every_contract_vector():
    """Vectors are consumed from the contract, never regenerated by the builder."""
    contract = _contract()
    seen = 0
    for entry in contract["dimensions"]:
        for vector in entry["vectors"]:
            seen += 1
            raw = jcs.parse(base64.b64decode(vector["raw_input_b64"], validate=True))
            built = identity.build_identity(entry["dimension"], raw, contract)
            assert built == vector["expected_identity"], vector["vector_id"]
            expected_bytes = base64.b64decode(vector["expected_basis_bytes_b64"],
                                              validate=True)
            assert jcs.serialize(built["basis"]) == expected_bytes, vector["vector_id"]
            assert built["digest"] == vector["expected_digest"], vector["vector_id"]
    assert seen == 15

    # A dimension or variant with no vector is a failure, not an omission.
    for entry in contract["dimensions"]:
        assert entry["vectors"], entry["dimension"]
        for variant in entry["variants"] or []:
            assert any(v["variant_id"] == variant["variant_id"]
                       for v in entry["vectors"]), variant["variant_id"]


