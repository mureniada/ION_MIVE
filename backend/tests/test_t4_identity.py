# T70 / T71 — the digest is recomputed, and absence is digested
# --------------------------------------------------------------------------- #

@guarded
def test_t70_every_identity_digest_is_sha256_of_its_canonical_basis():
    contract = _contract()
    for entry in contract["dimensions"]:
        for vector in entry["vectors"]:
            built = identity.build_identity(
                entry["dimension"],
                jcs.parse(base64.b64decode(vector["raw_input_b64"], validate=True)),
                contract)
            assert built["digest"] == hashlib.sha256(
                jcs.serialize(built["basis"])).hexdigest()


@guarded
def test_t71_absence_is_digested_and_two_dimensions_absences_differ():
    contract = _contract()
    absent_prompt = identity.build_identity("prompt", {"present": False}, contract)
    absent_context = identity.build_identity("context", {"present": False}, contract)

    assert absent_prompt["digest"] is not None
    assert absent_prompt["basis"]["basis_kind"] == "absence"
    assert absent_prompt["presence"] == "absent"
    assert absent_prompt["resolution_state"] == "explicitly_disabled"
    # Two absences of one dimension are equal; absences of two dimensions are not,
    # because `dimension` sits inside the basis.
    assert identity.build_identity("prompt", {"present": False}, contract) == absent_prompt
    assert absent_prompt["digest"] != absent_context["digest"]


@guarded
def test_t71b_a_present_input_cannot_be_recorded_as_absent():
    """Construction-level: a false absence fails parity, it is not merely unlikely."""
    contract = _contract()
    raw = {"bytes_b64": base64.b64encode(b"a real prompt").decode(), "present": True}
    built = identity.build_identity("prompt", raw, contract)
    assert built["presence"] == "present"
    assert built["basis"]["basis_kind"] == "content_reference"

    claimed_absent = identity.build_identity("prompt", {"present": False}, contract)
    assert claimed_absent != built, "a record asserting absence for this input fails parity"


