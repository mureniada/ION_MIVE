# T63 / T64 / T72 / T74 — sensitivity, by mutating raw input
# --------------------------------------------------------------------------- #

@guarded
def test_t63_every_configured_policy_dimension_is_sensitive_to_its_raw_configuration():
    """Only two policy dimensions are configured here; the other three are unobservable."""
    contract = _contract()

    dispatch = _raw_of(contract, "dispatch", "dispatch-v1")
    base = identity.build_identity("dispatch", dispatch, contract)
    for mutation in (
        {"order": ["openai", "gemini"]},        # a different call order
        {"mode": "parallel"},                   # a different dispatch mode
        {"configurable": True},                 # configured-on versus configured-off
    ):
        mutated = dict(dispatch, **mutation)
        rebuilt = identity.build_identity("dispatch", mutated, contract)
        assert rebuilt["digest"] != base["digest"], mutation
        assert rebuilt["basis"]["parameters"] != base["basis"]["parameters"]

    fallback = _raw_of(contract, "fallback", "fallback-v1")
    base = identity.build_identity("fallback", fallback, contract)
    # A configured "disabled" and a configured "enabled" state must differ.
    enabled = identity.build_identity("fallback", dict(fallback, enabled=True), contract)
    assert enabled["digest"] != base["digest"]
    assert enabled["basis"]["parameters"] != base["basis"]["parameters"]


@guarded
def test_t64_component_implementation_identity_is_sensitive_to_the_environment():
    contract = _contract()
    raw = _raw_of(contract, "implementation", "implementation-v1")
    base = identity.build_identity("implementation", raw, contract)

    # A last-digit change in one dependency version moves the digest.
    mutated = copy.deepcopy(raw)
    mutated["distributions"]["numpy_version"] = "2.5.2"
    assert identity.build_identity("implementation", mutated, contract)["digest"] \
        != base["digest"]

    # So does the interpreter version.
    mutated = copy.deepcopy(raw)
    mutated["python"] = "3.12.14"
    assert identity.build_identity("implementation", mutated, contract)["digest"] \
        != base["digest"]


